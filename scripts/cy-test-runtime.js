const { createHash, randomUUID } = require('crypto');
const { existsSync, mkdirSync, readdirSync, renameSync, writeFileSync } = require('fs');
const path = require('path');

const theme = (dependency, name, directory = 'themes') => ({
    dependency,
    file: `${directory}/${name}.js`,
    name,
});

const packages = {
    'plasma-b2c': { ...theme('@salutejs/plasma-tokens-b2c', 'dark'), typography: true },
    'plasma-giga': theme('@salutejs/plasma-themes', 'plasma_giga__light'),
    'plasma-web': theme('@salutejs/plasma-themes', 'plasma_web__light'),
    'plasma-homeds': theme('@salutejs/plasma-themes', 'plasma_homeds__light'),
    'sdds-cs': { ...theme('@salutejs/sdds-themes', 'sdds_cs__light'), engine: 'emotion' },
    'sdds-insol': theme('@salutejs/sdds-themes', 'sdds_insol__light'),
    'sdds-insol-next': theme('@salutejs/sdds-themes', 'sdds_insol_next__light'),
    'sdds-netology': theme('@salutejs/plasma-themes', 'plasma_b2c__light'),
    'sdds-bizcom': theme('@salutejs/sdds-themes', 'sdds_bizcom__light'),
    'sdds-serv': theme('@salutejs/sdds-themes', 'sdds_serv__light'),
    'sdds-scan': theme('@salutejs/sdds-themes', 'sdds_scan__light'),
    'sdds-os': theme('@salutejs-ds/sdds_os', 'sdds_os__light', 'theme/themes'),
    'sdds-platform-ai': theme('@salutejs/sdds-themes', 'sdds_platform_ai__light'),
    'sdds-finai': theme('@sddsjs/sdds_finai', 'sdds_finai_default__light', 'theme/themes'),
    'sdds-dfa': theme('@salutejs/sdds-themes', 'sdds_dfa__light'),
};

const generateTestRuntime = ({ packageName, rootDir = path.resolve(__dirname, '..') }) => {
    if (!Object.prototype.hasOwnProperty.call(packages, packageName)) {
        throw new Error(`Unsupported Cypress package: ${packageName}.`);
    }

    const selected = packages[packageName];
    const packageDir = path.join(rootDir, 'packages', packageName);
    const entry = path.join(packageDir, 'dist', selected.engine || 'styled-components', 'cjs', 'index.js');
    if (!existsSync(entry)) {
        throw new Error(`Build @salutejs/${packageName} and its dependencies before running Cypress.`);
    }

    const dependencyFile = (dependency, file) => {
        const manifest = require.resolve(`${dependency}/package.json`, {
            paths: [path.join(rootDir, 'utils', 'plasma-cy-utils'), rootDir],
        });
        const target = path.join(path.dirname(manifest), file);
        if (!existsSync(target)) {
            throw new Error(`Missing Cypress theme dependency: ${target}. Build the workspace dependencies first.`);
        }
        return target;
    };

    const themeFile = dependencyFile(selected.dependency, selected.file);
    const componentsDir = path.join(packageDir, 'src', 'components');
    // Preserve the existing component/component.config.ts lookup, including configs used by another spec.
    // COMPONENTS and --spec filter specs, not the configurations available to those specs.
    const configs = readdirSync(componentsDir, { withFileTypes: true })
        .filter((entryInfo) => entryInfo.isDirectory() || entryInfo.isSymbolicLink())
        .map(({ name }) => [name, path.join(componentsDir, name, `${name}.config.ts`)])
        .filter(([, file]) => existsSync(file))
        .sort(([left], [right]) => left.localeCompare(right));
    const quote = JSON.stringify;
    const styles = selected.typography
        ? [
              `createGlobalStyle(require(${quote(
                  dependencyFile('@salutejs/plasma-typo', 'lib/cjs/standard.js'),
              )}).standard)`,
              `createGlobalStyle(require(${quote(
                  dependencyFile('@salutejs/plasma-typo', 'lib/cjs/compatible.js'),
              )}).compatible)`,
              `createGlobalStyle(require(${quote(themeFile)})[${quote(selected.name)}])`,
          ]
        : [`createGlobalStyle(require(${quote(themeFile)})[${quote(selected.name)}])`];
    const source = `// Generated by scripts/cy-test-runtime.js. Do not edit.
const React = require('react');
const { createGlobalStyle } = require('styled-components');
const styles = [${styles.join(',\n')}];
const configs = {
${configs.map(([name, file]) => `${quote(name)}: () => require(${quote(file)})`).join(',\n')}
};
exports.isTestPackageSupported = (name) => name === ${quote(packageName)};
exports.getTestPackage = (name) => {
    if (!exports.isTestPackageSupported(name)) throw new Error('Cypress package does not match PACKAGE_NAME: ' + name);
    return require(${quote(entry)});
};
exports.TestTheme = () => React.createElement(React.Fragment, null, ...styles.map((Style) => React.createElement(Style)));
exports.getTestConfig = (component) => {
    if (!Object.prototype.hasOwnProperty.call(configs, component)) return null;
    try { return configs[component]().config; } catch { return null; }
};
`;
    const hash = createHash('sha256').update(source).digest('hex').slice(0, 16);
    const directory = path.join(rootDir, 'cypress', '.generated', packageName);
    const filename = path.join(directory, `testRuntime.${hash}.js`);
    if (!existsSync(filename)) {
        mkdirSync(directory, { recursive: true });
        const temporary = path.join(directory, `${process.pid}-${randomUUID()}.tmp`);
        writeFileSync(temporary, source);
        renameSync(temporary, filename);
    }

    return filename;
};

module.exports = { generateTestRuntime };
